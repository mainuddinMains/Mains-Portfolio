import { defineField, defineType } from "sanity";
import {
  contentGroups,
  coverImageField,
  endDateField,
  featuredField,
  galleryField,
  httpUrlValidation,
  linksField,
  orderField,
  slugField,
  startDateField,
  tagListField,
  videosField,
} from "../fields";

export const research = defineType({
  name: "research",
  title: "Research",
  type: "document",
  groups: [...contentGroups, { name: "publication", title: "Publication" }],
  fields: [
    defineField({ name: "title", title: "Title", type: "string", validation: (r) => r.required() }),
    slugField(),
    defineField({
      name: "summary",
      title: "Abstract / summary",
      type: "text",
      rows: 4,
      validation: (r) => r.required(),
    }),
    defineField({ name: "body", title: "Details", type: "richText" }),
    tagListField("areas", "Research areas (e.g. AI/ML, HPC)"),
    defineField({
      name: "status",
      title: "Status",
      type: "string",
      initialValue: "ongoing",
      options: {
        list: [
          { title: "Ongoing", value: "ongoing" },
          { title: "Completed", value: "completed" },
          { title: "Under review", value: "under-review" },
          { title: "Published", value: "published" },
        ],
        layout: "radio",
      },
      validation: (r) => r.required(),
    }),
    defineField({ name: "advisor", title: "Advisor", type: "string" }),
    defineField({ name: "institution", title: "Institution / lab", type: "string" }),
    defineField({
      name: "publication",
      title: "Publication",
      type: "object",
      group: "publication",
      fields: [
        defineField({ name: "venue", title: "Venue", type: "string" }),
        defineField({ name: "authors", title: "Authors", type: "string" }),
        defineField({ name: "year", title: "Year", type: "number" }),
        defineField({ name: "doi", title: "DOI", type: "string" }),
        defineField({
          name: "url",
          title: "Paper URL",
          type: "url",
          validation: httpUrlValidation,
        }),
      ],
    }),
    linksField,
    startDateField(),
    endDateField(),
    featuredField,
    orderField,
    coverImageField,
    galleryField,
    videosField,
  ],
  preview: { select: { title: "title", subtitle: "status", media: "coverImage" } },
});
